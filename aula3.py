"""
Python = Linguagem de Programação
Tipo de tipagem = Dinâmica / Forte
str -> string -> texto
Strings são textos que estão dentro de aspas
"""

print(1234)

# Aspas simples
print('Bruno RM')
print(1, 'Bruno "RM"')

# Aspas duplas
print("Bruno RM")
print(2, "Bruno 'RM'")

# Escape
print("Bruno \"RM\"")

# r
print(r"Bruno \"RM\"")